	/**
	 * Test whether a point exists within the boundaries of a polygons.
	 *
	 * @param polygon contours of a polygon
	 * @param point point to test
	 * @return {@code true} if, and only if, {@code point} lies on a border or inside {@code
	 * polygon}
	 */
	static boolean isInside(float[][] polygon, PointF point) {
		int k = 0;

		for (float[] contour : polygon) {
			int numPoly = contour.length / 2;
			float px = contour[0];
			float py = contour[1];

			Preconditions.checkArgument(
				px == contour[(numPoly - 1) * 2] && py == contour[(numPoly - 1) * 2 + 1],
				"invalid ring"
			);

			float u1 = px - point.x;
			float v1 = py - point.y;

			for (int i = 1; i < (numPoly - 1); i++) {
				float u2 = contour[i * 2] - point.x;
				float v2 = contour[i * 2 + 1] - point.y;

				if (v1 == 0 && v2 == 0) {
					if ((u2 <= 0 && u1 >= 0) || (u1 <= 0 && u2 >= 0))
						return true;
				} else if ((v2 >= 0 && v1 <= 0) || (v2 <= 0 && v1 >= 0)) {
					float det = u2 * v1 - u1 * v2;

					if (det == 0)
						return true;
					//noinspection ConstantValue
					if ((det > 0 && v2 > 0 && v1 <= 0) || (det < 0 && v2 <= 0 && v1 > 0))
						k++;
				}
				v1 = v2;
				u1 = u2;
			}
		}
		return (k % 2) != 0;
	}

	/**
	 * Test whether a point exists within the boundaries of zero or more polygons.
	 *
	 * @param geometry tuple of geometry bounding box and polygons geometry to test against
	 * @param point point to test for
	 * @return {@code true} if, and only if, {@code point} exists within {@code geometry}
	 */
	static boolean isInside(Pair<RectF, float[][][]> geometry, PointF point) {
		if (!geometry.first.contains(point.x, point.y))
			return false;
		for (float[][] polygon : geometry.second) {
			if (isInside(polygon, point))
				return true;
		}
		return false;
	}
